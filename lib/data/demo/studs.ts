const tones: DemoPhoto["tone"][] = ["navy", "clay", "sage", "sand"];

function portraits(
  slug: string,
  variant: DemoPhoto["variant"],
  count: number,
  subject: string,
): DemoPhoto[] {
  return Array.from({ length: count }, (_, index) => ({
    id: `${slug}-photo-${index + 1}`,
    tone: tones[index % tones.length] ?? "navy",
    variant,
    alt: `Illustrative portrait ${index + 1} of ${subject}. Sample image, not a real photograph.`,
  }));
}

